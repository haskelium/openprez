import { posix } from "node:path";
import { transformWithOxc } from "vite";
import { STANDALONE_ENTRIES, STANDALONE_MANIFEST_FILE } from "./manifest.ts";

const SCRIPT_TAG = /<script\b[^>]*>[\s\S]*?<\/script>/gi;
const LINK_TAG = /<link\b[^>]*>/gi;
const SCRIPT_END_TAG = /<\/script(?=[\t\n\f\r />])/i;
const STYLE_END_TAG = /<\/style(?=[\t\n\f\r />])/i;
const LOCAL_CSS_URL = /url\(\s*(["']?)(?!data:|https?:|#)([^"')]+)\1\s*\)/i;

/** Validate build provenance and ensure the manifest exactly describes the available output. */
export function validateStandaloneManifest(manifest, flavor, availableFiles) {
  const expectedEntry = STANDALONE_ENTRIES[flavor];
  if (!expectedEntry) throw new Error(`Unknown standalone flavor: ${flavor}`);
  if (!manifest || typeof manifest !== "object" || Array.isArray(manifest)) {
    throw new Error("Standalone build manifest must be a JSON object");
  }
  if (manifest.version !== 1) {
    throw new Error(`Unsupported standalone manifest version: ${String(manifest.version)}`);
  }
  if (manifest.flavor !== flavor) {
    throw new Error(
      `Expected a ${flavor} build, but the manifest identifies ${String(manifest.flavor)}`,
    );
  }
  if (manifest.entry !== expectedEntry) {
    throw new Error(
      `Expected standalone entry ${expectedEntry}, received ${String(manifest.entry)}`,
    );
  }
  if (!Array.isArray(manifest.files) || manifest.files.length === 0) {
    throw new Error("Standalone build manifest must list emitted files");
  }

  const listed = new Set();
  for (const file of manifest.files) {
    if (!isSafeRelativePath(file)) {
      throw new Error(`Unsafe path in standalone build manifest: ${String(file)}`);
    }
    if (listed.has(file)) throw new Error(`Duplicate file in standalone build manifest: ${file}`);
    listed.add(file);
  }
  if (!listed.has(expectedEntry)) {
    throw new Error(`Standalone build manifest does not include ${expectedEntry}`);
  }

  const available = new Set(availableFiles);
  const missing = [...listed].filter((file) => !available.has(file));
  if (missing.length > 0) {
    throw new Error(`Standalone build is missing manifest files: ${missing.join(", ")}`);
  }
  const unlisted = [...available].filter(
    (file) => file !== STANDALONE_MANIFEST_FILE && !listed.has(file),
  );
  if (unlisted.length > 0) {
    throw new Error(
      `Standalone build contains files not described by its manifest: ${unlisted.join(", ")}`,
    );
  }

  return [...listed];
}

/**
 * Assemble a standalone document from validated Vite output without touching the filesystem.
 * The standalone Vite build inlines every asset itself, so only the entry, its scripts and its
 * stylesheets may be emitted; anything else means an asset escaped the artifact.
 */
export async function assembleStandaloneHtml({ manifest, flavor, files }) {
  const fileNames = validateStandaloneManifest(manifest, flavor, files.keys());
  const uninlined = fileNames.filter(
    (fileName) => fileName !== manifest.entry && !/\.(?:js|css)$/.test(fileName),
  );
  if (uninlined.length > 0) {
    throw new Error(
      `Standalone build emitted files that were not inlined: ${uninlined.join(", ")}; rebuild with the matching pnpm prez command`,
    );
  }

  const text = (fileName) => textContent(files.get(fileName), fileName);
  const stylesheets = new Map();
  const scripts = new Map();
  for (const fileName of fileNames) {
    if (fileName.endsWith(".css"))
      stylesheets.set(fileName, serializeStylesheet(fileName, text(fileName)));
    if (fileName.endsWith(".js"))
      scripts.set(fileName, await serializeScript(fileName, text(fileName)));
  }

  const html = inlineScripts(inlineStylesheets(text(manifest.entry), stylesheets), scripts);
  assertSelfContained(html, scripts.size + countInlineScripts(text(manifest.entry)));
  return `${html.trim()}\n<!-- Generated by pnpm prez; do not edit. -->\n`;
}

function isSafeRelativePath(file) {
  return (
    typeof file === "string" &&
    file.length > 0 &&
    !file.includes("\\") &&
    !posix.isAbsolute(file) &&
    posix.normalize(file) === file &&
    file !== ".." &&
    !file.startsWith("../") &&
    file !== STANDALONE_MANIFEST_FILE
  );
}

function textContent(value, fileName) {
  if (typeof value === "string") return value;
  if (value instanceof Uint8Array) return Buffer.from(value).toString("utf8");
  throw new Error(`Standalone emitted file is missing or invalid: ${fileName}`);
}

function assetKeyFromUrl(url) {
  return decodeURIComponent(url.split(/[?#]/, 1)[0]).replace(/^\.?\/+/, "");
}

/** Escape closing-style prefixes with a CSS escape that decodes to the same characters. */
function serializeStylesheet(fileName, css) {
  const unresolved = css.match(LOCAL_CSS_URL);
  if (unresolved) {
    throw new Error(`Stylesheet ${fileName} still references a local file: ${unresolved[2]}`);
  }
  const serialized = css.replace(
    /<\/(style)(?=[\t\n\f\r />])/gi,
    (_match, name) => `\\3C /${name}`,
  );
  if (STYLE_END_TAG.test(serialized)) {
    throw new Error(`Unsafe closing style tag remains in emitted stylesheet: ${fileName}`);
  }
  return serialized;
}

/** Re-emit JavaScript through Vite's HTML-safe code generator, preserving runtime values. */
async function serializeScript(fileName, source) {
  const { code } = await transformWithOxc(source, fileName, { target: "esnext" });
  if (SCRIPT_END_TAG.test(code)) {
    throw new Error(`Unsafe closing script tag remains in emitted JavaScript: ${fileName}`);
  }
  return code;
}

// Replacement callbacks, never replacement strings: bundled code contains `$$`, `$&` and `` $` ``,
// which String.replace would otherwise expand into fragments of the surrounding document.
function inlineStylesheets(html, stylesheets) {
  return html.replace(LINK_TAG, (tag) => {
    const rel = tag.match(/\brel=["']([^"']+)["']/i)?.[1].toLowerCase();
    if (rel === "modulepreload") return "";
    if (rel !== "stylesheet") return tag;
    const href = tag.match(/\bhref=["']([^"']+)["']/i)?.[1];
    if (!href) throw new Error(`Stylesheet link has no href: ${tag}`);
    const css = stylesheets.get(assetKeyFromUrl(href));
    if (css === undefined) throw new Error(`Could not find emitted stylesheet: ${href}`);
    return `<style>\n${css}\n</style>`;
  });
}

function inlineScripts(html, scripts) {
  return html.replace(SCRIPT_TAG, (tag) => {
    const src = tag.match(/\bsrc=["']([^"']+)["']/i)?.[1];
    if (!src) return tag;
    const code = scripts.get(assetKeyFromUrl(src));
    if (code === undefined) throw new Error(`Could not find emitted script: ${src}`);
    return `<script type="module">\n${code}\n</script>`;
  });
}

function countInlineScripts(entryHtml) {
  return [...entryHtml.matchAll(SCRIPT_TAG)].filter(([tag]) => !/\bsrc=/i.test(tag)).length;
}

/** The assembled document must have exactly the expected script elements and no external refs. */
function assertSelfContained(html, expectedScripts) {
  // Script content cannot contain a closing tag (guarded above), so each match is one element.
  const scriptElements = [...html.matchAll(SCRIPT_TAG)].length;
  if (scriptElements !== expectedScripts) {
    throw new Error(
      `Standalone HTML has ${scriptElements} script elements, expected ${expectedScripts}`,
    );
  }
  const markupOnly = html.replace(SCRIPT_TAG, "").replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "");
  if (/<script\b[^>]+\bsrc\s*=/i.test(markupOnly)) {
    throw new Error("Standalone HTML still contains an external script reference");
  }
  if (/<link\b[^>]*\brel=["']stylesheet["'][^>]*\bhref\s*=/i.test(markupOnly)) {
    throw new Error("Standalone HTML still contains an external stylesheet reference");
  }
}
